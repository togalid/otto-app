import { mkdir, readFile, rename, writeFile } from 'node:fs/promises'
import { homedir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { discoverDrumKits } from '../server/drum-kits.mjs'

const source = process.argv[2] ?? join(homedir(), 'Desktop', 'Otto用素材', '電子ドラムサンプル')
const destination = fileURLToPath(new URL('../dist/samples/', import.meta.url))
const manifest = fileURLToPath(new URL('../dist/drum-kit-manifest.js', import.meta.url))
const kits = await discoverDrumKits(source)
if (!kits.length) throw new Error('WAVのあるドラムキットが見つかりません。既存の同梱設定は変更しません。')

const assets = []
for (const kit of kits) {
  for (const sample of kit.samples) {
    const bytes = await readFile(join(source, kit.id, sample.file))
    if (bytes.length < 44 || bytes.length > 4 * 1024 * 1024 ||
        bytes.toString('ascii', 0, 4) !== 'RIFF' || bytes.toString('ascii', 8, 12) !== 'WAVE') {
      throw new Error(`WAVを確認してください: ${kit.name}/${sample.file}`)
    }
    assets.push({folder:join(destination, kit.id), file:sample.file, bytes})
  }
}
for (const asset of assets) {
  await mkdir(asset.folder, {recursive:true})
  const target = join(asset.folder, asset.file)
  const temporary = target + '.oto-tmp'
  await writeFile(temporary, asset.bytes)
  await rename(temporary, target)
}
const contents = '// Generated by npm run drum:kits.\n' +
  '/** @type {{id:string,name:string,samples:{id:number,label:string,file:string}[],skipped:number}[]} */\n' +
  'export const bundledDrumKits = ' + JSON.stringify(kits, null, 2) + '\n'
await writeFile(manifest + '.tmp', contents)
await rename(manifest + '.tmp', manifest)
console.log(kits.map(kit => kit.name + ': ' + kit.samples.length + ' WAV').join('\n'))
